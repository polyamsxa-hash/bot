import os
import asyncio
import logging

from aiogram import Bot, Dispatcher, types
import google.generativeai as genai

# ======================
# НАСТРОЙКИ
# ======================

logging.basicConfig(level=logging.INFO)

BOT_TOKEN = os.getenv("BOT_TOKEN")
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")

if not BOT_TOKEN or not GEMINI_API_KEY:
    raise ValueError("BOT_TOKEN и GEMINI_API_KEY должны быть указаны!")

# Gemini (старый, но рабочий вариант)
genai.configure(api_key=GEMINI_API_KEY)
model = genai.GenerativeModel("gemini-2.5-flash")

bot = Bot(token=BOT_TOKEN)
dp = Dispatcher()

# ======================
# ПРОМПТ (менеджер продаж)
# ======================

SYSTEM_PROMPT = """
Ты — senior помощник менеджера по продажам премиальной техники.

Мы продаём:
- Apple (iPhone, MacBook, AirPods, Apple Watch)
- Samsung Galaxy
- PlayStation 5 / Xbox
- Dyson / Dreame
- аксессуары и техника

========================
ТВОЯ РОЛЬ
========================
Ты НЕ поддержка и НЕ консультант.
Ты — ИНСТРУМЕНТ ДЛЯ ЗАКРЫТИЯ ПРОДАЖ.

Твоя задача:
- понимать возражение клиента
- помогать менеджеру закрывать сделку
- переводить диалог к покупке

========================
ЗАПРЕЩЕНО
========================
- общие вопросы ("чем помочь", "расскажите подробнее")
- поведение как техподдержка
- уход от продажи в информацию
- длинные объяснения

========================
ФОРМАТ ОТВЕТА (СТРОГО)
========================

1. ПРИСОЕДИНЕНИЕ (1 короткая фраза под ситуацию клиента)

2. 3–5 ПРОДАЮЩИХ ВОПРОСОВ В ФОРМАТЕ "ИЛИ — ИЛИ"
(вопросы должны вскрывать причину и вести к покупке)

3. ПОДСКАЗКА МЕНЕДЖЕРУ (1 короткое действие)

========================
ПРАВИЛА ВОПРОСОВ
========================
- всегда использовать "или — или"
- вопросы должны быть про:
  • цену / выгоду
  • сравнение
  • выбор модели
  • сомнение
  • страх ошибки
  • сроки покупки
- никакой воды

========================
ЛОГИКА ВОЗРАЖЕНИЙ
========================

"дорого" →
- сравнивает цены или ищет выгоду
- не видит ценности

"думаю" →
- нет уверенности или срочности

"сравниваю" →
- ищет дешевле или боится ошибиться

"посоветуюсь" →
- нет финального решения

"позже" →
- нет срочности

========================
ПРИМЕР

Клиент: "дорого"

Ответ:

Понимаю, важно взять максимально выгодно.

Вы сравниваете с другими магазинами или больше смотрите на бюджет?
Вопрос в цене или вы хотите лучшую модель по характеристикам?
Рассматриваете экономию или максимальное качество?

Подсказка: предложи трейд-ин или рассрочку

========================
СТИЛЬ
========================
- только русский язык
- коротко и по делу
- как опытный менеджер
- без markdown, без символов ###, *, |
"""

# ======================
# ОБРАБОТЧИК
# ======================

@dp.message()
async def handler(message: types.Message):
    text = message.text.strip()

    if not text:
        await message.answer("Напиши сообщение клиента")
        return

    try:
        prompt = f"""
{SYSTEM_PROMPT}

Клиент: {text}
"""

        response = model.generate_content(prompt)
        answer = response.text.strip()

        # чистка мусора
        for bad in ["###", "*", "|"]:
            answer = answer.replace(bad, "")

        await message.answer(answer)

    except Exception as e:
        logging.error(e)
        await message.answer("Ошибка ИИ, попробуй ещё раз")

# ======================
# ЗАПУСК
# ======================

async def main():
    print("🚀 Бот запущен")
    await dp.start_polling(bot)

if __name__ == "__main__":
    asyncio.run(main())
