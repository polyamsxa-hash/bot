import os
import asyncio
import logging
from aiogram import Bot, Dispatcher, types

logging.basicConfig(level=logging.INFO)

BOT_TOKEN = os.getenv("BOT_TOKEN")

if not BOT_TOKEN:
    raise ValueError("Нет BOT_TOKEN")

bot = Bot(token=BOT_TOKEN)
dp = Dispatcher()

# ======================
# СКРИПТЫ
# ======================

def handle_message(text: str):
    t = text.lower()

    # ДОРОГО
    if "дорог" in t:
        return """Понимаю, важно взять максимально выгодно.

Вы сейчас сравниваете цены или выбираете модель?
Вопрос в бюджете или в характеристиках?
Смотрите дешевле или хотите лучший вариант?

Подсказка: предложи трейд-ин, рассрочку или бонус."""

    # ДУМАЮ
    if "дума" in t:
        return """Понимаю, важно всё спокойно обдумать.

Остались вопросы или просто нужно время?
Вы выбираете между вариантами или пока не уверены?
Что-то смущает или просто не спешите?

Подсказка: попробуй выявить реальное сомнение."""

    # СРАВНИВАЮ
    if "сравни" in t or "дешевле" in t:
        return """Понимаю, важно выбрать лучший вариант.

Сравниваете по цене или по характеристикам?
Смотрите разные магазины или выбираете модель?
Важно дешевле или надёжнее?

Подсказка: подчеркни преимущества и гарантию."""

    # ПОЗЖЕ
    if "позже" in t or "потом" in t:
        return """Понимаю, не всегда есть срочность.

Планируете покупку позже или пока просто присматриваетесь?
Ждёте снижения цены или выбираете вариант?
Есть конкретные сроки или пока нет?

Подсказка: добавь ограничение по времени или наличию."""

    # СОВЕТОВАТЬСЯ
    if "посовет" in t:
        return """Понимаю, важно принять решение вместе.

Вы хотите уточнить мнение или есть сомнения?
Вопрос в модели или в цене?
Сравниваете варианты или выбираете один?

Подсказка: закрепи выбор за клиентом."""

    # ВЫБОР МОДЕЛИ
    if "что лучше" in t or "какой" in t:
        return """Давайте подберём оптимальный вариант.

Для вас важнее цена или характеристики?
Рассматриваете компактность или мощность?
Нужен вариант попроще или максимально топ?

Подсказка: сузь выбор до 2 моделей."""

    # ПО УМОЛЧАНИЮ
    return """Понимаю, давайте разберёмся.

Вы выбираете модель или сравниваете цены?
Вопрос в бюджете или в характеристиках?
Планируете покупку сейчас или позже?

Подсказка: уточни потребность клиента."""

# ======================
# ОБРАБОТЧИК
# ======================

@dp.message()
async def handler(message: types.Message):
    text = message.text.strip()

    if not text:
        await message.answer("Напиши сообщение клиента")
        return

    answer = handle_message(text)
    await message.answer(answer)

# ======================
# ЗАПУСК
# ======================

async def main():
    print("🚀 Бот без ИИ запущен")
    await dp.start_polling(bot)

if __name__ == "__main__":
    asyncio.run(main())
